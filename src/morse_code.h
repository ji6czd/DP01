#pragma once

// 欧文モールス符号の通知音。この端末は状態表示に液晶を使わないため、起動完了・
// エラー等の通知を短いモールス符号のサイドトーンで鳴らす。
//
// PCM(24kHz, int16, ステレオ)は実行時に合成する。決まった波形(短点・長点・点間・
// 文字間)の並びにすぎないので、1周期ぶんの正弦波テーブルだけ持ち、要素ごとに
// トーンか無音を書き出してi2s_speakerへenqueueする。ヒープもフラッシュの大きな
// データも使わない。
//
// i2s_speakerは常に1本のストリームだけを流す前提(単一プロデューサ)なので、
// 再生中はradio_streamを一時停止させ、この間だけモールスが唯一の書き込み元になる。
// 実際の合成・書き込みは専用タスクが行うため、morsePlay()はブロックしない
// (loop()のキー入力処理を止めない)。

// 起動時に1回呼ぶ。正弦波テーブルを焼き、再生専用タスクとリクエストキューを生成する。
// i2sSpeakerBegin()の後に呼ぶこと。
bool morseBegin();

// textをモールス符号で鳴らす(非同期・ノンブロッキング)。
// 対応文字: A-Z / a-z(大文字化して扱う) / 0-9 / 半角スペース(語間) /
//           記号 . , ? / - = + @ : 。未対応の文字は読み飛ばす。
// textはconfig::kMorseMaxTextLenで切り捨てる。リクエストキューが一杯なら
// falseを返してそのリクエストを捨てる(呼び出し元は戻り値を無視してよい)。
bool morsePlay(const char* text);
