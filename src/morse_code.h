#pragma once

#include <cstdint>

// 欧文モールス符号の通知音。この端末は状態表示に液晶を使わないため、起動完了・
// エラー等の通知を短いモールス符号のサイドトーンで鳴らす。
//
// PCM(24kHz, int16, ステレオ)は実行時に合成する。決まった波形(短点・長点・点間・
// 文字間)の並びにすぎないので、要素ごとにsinfで正弦波かトーンの無い無音を書き出して
// i2s_speakerへenqueueする。ヒープもフラッシュの大きな
// データも使わない。
//
// i2s_speakerは常に1本のストリームだけを流す前提(単一プロデューサ)なので、
// 再生中はradio_streamを一時停止させ、この間だけモールスが唯一の書き込み元になる。
// 実際の合成・書き込みは専用タスクが行うため、morsePlay()はブロックしない
// (loop()のキー入力処理を止めない)。

// 操作の合図に使う音階の数。pitchは1(最低音)〜kMorsePitchCount(最高音)で指定する。
inline constexpr uint8_t kMorsePitchCount = 10;

// 起動時に1回呼ぶ。正弦波テーブルを焼き、再生専用タスクとリクエストキューを生成する。
// i2sSpeakerBegin()の後に呼ぶこと。
bool morseBegin();

// textをモールス符号で鳴らす(非同期・ノンブロッキング)。
// 対応文字: A-Z / a-z(大文字化して扱う) / 0-9 / 半角スペース(語間) /
//           記号 . , ? / - = + @ : 。未対応の文字は読み飛ばす。
// textは長すぎると切り捨てる(上限はmorse_code.cppのkMorseMaxTextLen)。リクエストキューが一杯なら
// falseを返してそのリクエストを捨てる(呼び出し元は戻り値を無視してよい)。
//
// pitchは音の高さ。0なら既定(A5=880Hz)、1〜kMorsePitchCountは音階(平均律、A5=880Hz)で、
// 1がC5(523Hz)、大きいほど高く、10がE6(1319Hz)。範囲外はfalse。
// 高さはリクエストごとに持つので、再生中に次のリクエストを積んでも途中で音程は変わらない。
// 短い合図は "e"(短1つ)、"i"(短2つ)、"t"(長1つ)、"m"(長2つ)で足りる。
bool morsePlay(const char* text, uint8_t pitch = 0);

// morsePlay()で積んだ音がすべて鳴り終えるまで(末尾がI2Sから出切るまで)待つ。呼んだタスクを
// ブロックする。timeoutMsまでに終わらなければfalse。
// i2s_speakerのサンプルレートは1つしか持てず、モールス(24kHz)と別レートの音声をリングに
// 混ぜると音程が狂うので、音声の再生を再開する前には必ず待つこと。
bool morseWaitIdle(uint32_t timeoutMs);
